export type ServiceStatus = "available" | "option" | "consult";

export type Service = {
  id: string;
  /** カード見出し */
  name: string;
  /** カードの1行説明 */
  summary: string;
  /** アイコン代わりの絵文字（装飾なので aria-hidden で出す） */
  emoji: string;
  /** 媒体資料に載せている金額。サイトに出すかは SHOW_PRICES 次第 */
  price: string;
  /** 料金の下に出す補足 */
  priceNote?: string;
  status: ServiceStatus;
  /** サービス詳細ページで出す内容リスト */
  includes: string[];
  /** サービス詳細ページの本文（段落ごとの配列） */
  body: string[];
  /** 想定される使い方の例 */
  examples?: string[];
};

